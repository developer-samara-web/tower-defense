export function formatUpdateDate(iso: string): string {
	return new Intl.DateTimeFormat('ru-RU', {
		day: 'numeric',
		month: 'long',
		year: 'numeric',
		timeZone: 'UTC',
	})
		.format(new Date(`${iso}T00:00:00Z`))
		.replace(/\s*г\.$/, '')
}
